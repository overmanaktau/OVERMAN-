-- Сгорание бонусов только с разрешения владельца (17.10.2026): ночью бот не списывает сам, а присылает владельцу запрос
-- «к сгоранию N клиентов, X бонусов» с кнопками «Разрешить» / «Отклонить»; после «Разрешить» списание идёт порциями (задание каждые 5 минут)
-- и в конце приходит итог. Пишет и читает только сервер (RLS без политик).
create table if not exists public.kassa_bonus_expiry_requests (
  id bigint generated by default as identity primary key,
  run_date date not null,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'done')),
  clients int not null default 0,          -- сколько клиентов было в запросе
  total numeric not null default 0,         -- сколько бонусов предлагалось сжечь
  pending_ids jsonb not null default '[]',  -- клиенты (id МойСклад), которых ещё предстоит обработать
  error_ids jsonb not null default '[]',    -- по кому была ошибка
  written int not null default 0,           -- сколько клиентов уже обнулено
  written_total numeric not null default 0, -- сколько бонусов уже списано
  created_at timestamptz not null default now(),
  decided_at timestamptz,
  decided_by text,
  finished_at timestamptz
);
alter table public.kassa_bonus_expiry_requests enable row level security;

alter table public.kassa_bonus_expiry_log add column if not exists request_id bigint;
