-- «Оплаты» (Настройки → Оплаты): постоянные расходы на услуги и лицензии (вайфай, лицензия МойСклад и т. п.) со сроком, до которого оплачено, —
-- чтобы заранее знать, что и куда платить. Права — раздел settings.payments.
drop table if exists public.fin_services;
create table if not exists public.pay_services (
  id bigint generated by default as identity primary key,
  name text not null,                        -- что оплачивать
  pay_to text,                               -- куда платить (кому, где, реквизиты)
  amount numeric,                            -- сумма платежа, ₸
  store text references public.stores(code), -- null — общий для всех магазинов
  paid_until date not null,                  -- срок: до какого числа оплачено
  comment text,
  created_at timestamptz not null default now()
);
create index if not exists pay_services_paid_until_idx on public.pay_services (paid_until);

alter table public.pay_services enable row level security;
drop policy if exists pay_services_select on public.pay_services;
create policy pay_services_select on public.pay_services
  for select using (
    public.has_access('settings.payments', 'view')
    and (store is null and public.has_all_stores_access() or store is not null and public.has_store_access(store))
  );
drop policy if exists pay_services_write on public.pay_services;
create policy pay_services_write on public.pay_services
  for all using (
    public.has_access('settings.payments', 'edit')
    and (store is null and public.has_all_stores_access() or store is not null and public.has_store_access(store))
  )
  with check (
    public.has_access('settings.payments', 'edit')
    and (store is null and public.has_all_stores_access() or store is not null and public.has_store_access(store))
  );

-- раздел «Оплаты» больше не в «Финансах»: список прав для просмотра финансов как был до него
create or replace function public.has_finance_view()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.has_access('finance.overview', 'view')
      or public.has_access('finance.dds', 'view')
      or public.has_access('finance.opiu', 'view')
      or public.has_access('finance.debts', 'view')
      or public.has_access('finance.planned', 'view')
      or public.has_access('finance.settings', 'view');
$$;
