-- ── RLS ──────────────────────────────────────────────────────────────────
-- Справочники (счета, статьи, партнёры, поставщики, настройки, план): читает
-- любой, кто видит хотя бы один финансовый раздел; пишет — finance.settings
-- (план ОПИУ — finance.opiu) с правом edit.
-- Операции, долги, платежи: по правам раздела и доступу к магазину
-- (операция без магазина — только тем, у кого доступ ко всем магазинам).

create or replace function public.has_finance_view()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.has_access('finance.overview', 'view')
      or public.has_access('finance.dds', 'view')
      or public.has_access('finance.opiu', 'view')
      or public.has_access('finance.debts', 'view')
      or public.has_access('finance.planned', 'view')
      or public.has_access('finance.settings', 'view');
$$;

create or replace function public.has_all_stores_access()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select not exists (
    select 1 from public.stores s where not public.has_store_access(s.code)
  );
$$;

do $$
declare
  t text;
begin
  foreach t in array array['fin_accounts', 'fin_categories', 'fin_partners', 'fin_suppliers', 'fin_settings'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists %I on public.%I', t || '_select', t);
    execute format('create policy %I on public.%I for select using (public.has_finance_view())', t || '_select', t);
    execute format('drop policy if exists %I on public.%I', t || '_write', t);
    execute format(
      'create policy %I on public.%I for all using (public.has_access(''finance.settings'', ''edit'')) with check (public.has_access(''finance.settings'', ''edit''))',
      t || '_write', t
    );
  end loop;
end $$;

-- План ОПИУ
alter table public.fin_pnl_plan enable row level security;
drop policy if exists fin_pnl_plan_select on public.fin_pnl_plan;
create policy fin_pnl_plan_select on public.fin_pnl_plan
  for select using (public.has_access('finance.opiu', 'view') and (store is null or public.has_store_access(store)));
drop policy if exists fin_pnl_plan_write on public.fin_pnl_plan;
create policy fin_pnl_plan_write on public.fin_pnl_plan
  for all using (public.has_access('finance.opiu', 'edit') and (store is null or public.has_store_access(store)))
  with check (public.has_access('finance.opiu', 'edit') and (store is null or public.has_store_access(store)));

-- Операции
alter table public.fin_operations enable row level security;
drop policy if exists fin_operations_select on public.fin_operations;
create policy fin_operations_select on public.fin_operations
  for select using (
    (public.has_access('finance.dds', 'view') or public.has_access('finance.overview', 'view')
      or public.has_access('finance.opiu', 'view') or public.has_access('finance.debts', 'view')
      or public.has_access('finance.planned', 'view'))
    and (store is null and public.has_all_stores_access() or store is not null and public.has_store_access(store))
  );
drop policy if exists fin_operations_write on public.fin_operations;
create policy fin_operations_write on public.fin_operations
  for all using (
    (public.has_access('finance.dds', 'edit') or public.has_access('finance.debts', 'edit') or public.has_access('finance.planned', 'edit'))
    and (store is null and public.has_all_stores_access() or store is not null and public.has_store_access(store))
  )
  with check (
    (public.has_access('finance.dds', 'edit') or public.has_access('finance.debts', 'edit') or public.has_access('finance.planned', 'edit'))
    and (store is null and public.has_all_stores_access() or store is not null and public.has_store_access(store))
  );

-- Долги
alter table public.fin_debts enable row level security;
drop policy if exists fin_debts_select on public.fin_debts;
create policy fin_debts_select on public.fin_debts
  for select using (
    (public.has_access('finance.debts', 'view') or public.has_access('finance.overview', 'view'))
    and public.has_store_access(store)
  );
drop policy if exists fin_debts_write on public.fin_debts;
create policy fin_debts_write on public.fin_debts
  for all using (public.has_access('finance.debts', 'edit') and public.has_store_access(store))
  with check (public.has_access('finance.debts', 'edit') and public.has_store_access(store));

alter table public.fin_debt_payments enable row level security;
drop policy if exists fin_debt_payments_select on public.fin_debt_payments;
create policy fin_debt_payments_select on public.fin_debt_payments
  for select using (
    exists (select 1 from public.fin_debts d where d.id = debt_id and public.has_store_access(d.store))
    and (public.has_access('finance.debts', 'view') or public.has_access('finance.overview', 'view'))
  );
drop policy if exists fin_debt_payments_write on public.fin_debt_payments;
create policy fin_debt_payments_write on public.fin_debt_payments
  for all using (
    public.has_access('finance.debts', 'edit')
    and exists (select 1 from public.fin_debts d where d.id = debt_id and public.has_store_access(d.store))
  )
  with check (
    public.has_access('finance.debts', 'edit')
    and exists (select 1 from public.fin_debts d where d.id = debt_id and public.has_store_access(d.store))
  );

-- Плановые платежи
alter table public.fin_planned_payments enable row level security;
drop policy if exists fin_planned_select on public.fin_planned_payments;
create policy fin_planned_select on public.fin_planned_payments
  for select using (
    (public.has_access('finance.planned', 'view') or public.has_access('finance.overview', 'view'))
    and (store is null and public.has_all_stores_access() or store is not null and public.has_store_access(store))
  );
drop policy if exists fin_planned_write on public.fin_planned_payments;
create policy fin_planned_write on public.fin_planned_payments
  for all using (
    public.has_access('finance.planned', 'edit')
    and (store is null and public.has_all_stores_access() or store is not null and public.has_store_access(store))
  )
  with check (
    public.has_access('finance.planned', 'edit')
    and (store is null and public.has_all_stores_access() or store is not null and public.has_store_access(store))
  );

