-- Раздел «Финансы»: счета, статьи (дерево «пункт → подпункт»), партнёры, поставщики,
-- операции (основа ДДС), долги (между магазинами / магазин ↔ поставщик /
-- партнёр ↔ магазин), плановые платежи, план ОПИУ и настройки.
-- Выручка и себестоимость в ОПИУ берутся из МойСклад автоматически
-- (moysklad_sales_daily), поэтому в операции их вносить не нужно.
-- Доступ: раздел finance.* — просмотр / внесение (admin и owner видят всё).

-- ── Счета ────────────────────────────────────────────────────────────────
create table if not exists public.fin_accounts (
  id bigint generated by default as identity primary key,
  name text not null,
  kind text not null default 'cash' check (kind in ('cash', 'bank', 'card', 'other')),
  store text references public.stores(code), -- null = общий счёт компании
  opening_balance numeric not null default 0,
  opening_date date not null default current_date,
  active boolean not null default true,
  sort integer not null default 0,
  created_at timestamptz not null default now()
);

-- ── Статьи: пункт (parent_id is null) → подпункт ─────────────────────────
-- opiu_group: куда статья попадает в ОПИУ; null — не входит в ОПИУ (движение
-- капитала: займы, взносы и выплаты партнёрам, переносы).
create table if not exists public.fin_categories (
  id bigint generated by default as identity primary key,
  parent_id bigint references public.fin_categories(id) on delete restrict,
  name text not null,
  kind text not null check (kind in ('income', 'expense')),
  opiu_group text check (opiu_group in ('revenue', 'cogs', 'opex', 'other_income', 'other_expense', 'tax')),
  active boolean not null default true,
  sort integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.fin_partners (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text,
  note text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.fin_suppliers (
  id bigint generated by default as identity primary key,
  name text not null,
  bin text,
  phone text,
  payment_terms_days integer, -- отсрочка платежа по договору
  note text,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- ── Операции (ДДС) ───────────────────────────────────────────────────────
-- kind: income — приход, expense — расход, transfer — перевод между счетами
-- (в ДДС не считается ни доходом, ни расходом, меняет только остатки счетов).
create table if not exists public.fin_operations (
  id bigint generated by default as identity primary key,
  op_date date not null,
  kind text not null check (kind in ('income', 'expense', 'transfer')),
  amount numeric not null check (amount > 0),
  account_id bigint not null references public.fin_accounts(id),
  to_account_id bigint references public.fin_accounts(id), -- только для transfer
  category_id bigint references public.fin_categories(id),
  store text references public.stores(code),
  supplier_id bigint references public.fin_suppliers(id),
  partner_id bigint references public.fin_partners(id),
  debt_id bigint, -- ссылка на fin_debts (если операция — погашение долга)
  comment text,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now()
);
create index if not exists fin_operations_date_idx on public.fin_operations (op_date);
create index if not exists fin_operations_account_idx on public.fin_operations (account_id);

-- ── Долги ────────────────────────────────────────────────────────────────
-- kind: store_store — между магазинами, supplier — магазин ↔ поставщик,
-- partner — партнёр ↔ магазин. direction: payable — магазин (store) должен,
-- receivable — должны магазину. Для store_store store = кто должен
-- (payable) / кому должны (receivable), counterparty_store — вторая сторона.
create table if not exists public.fin_debts (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('store_store', 'supplier', 'partner')),
  direction text not null default 'payable' check (direction in ('payable', 'receivable')),
  store text not null references public.stores(code),
  counterparty_store text references public.stores(code),
  supplier_id bigint references public.fin_suppliers(id),
  partner_id bigint references public.fin_partners(id),
  amount numeric not null check (amount > 0),
  debt_date date not null default current_date,
  due_date date,
  comment text,
  closed boolean not null default false,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now()
);

create table if not exists public.fin_debt_payments (
  id bigint generated by default as identity primary key,
  debt_id bigint not null references public.fin_debts(id) on delete cascade,
  pay_date date not null,
  amount numeric not null check (amount > 0),
  operation_id bigint references public.fin_operations(id) on delete set null,
  comment text,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now()
);
create index if not exists fin_debt_payments_debt_idx on public.fin_debt_payments (debt_id);

-- ── Плановые платежи ─────────────────────────────────────────────────────
create table if not exists public.fin_planned_payments (
  id bigint generated by default as identity primary key,
  due_date date not null,
  kind text not null default 'expense' check (kind in ('income', 'expense')),
  amount numeric not null check (amount > 0),
  category_id bigint references public.fin_categories(id),
  store text references public.stores(code),
  supplier_id bigint references public.fin_suppliers(id),
  partner_id bigint references public.fin_partners(id),
  account_id bigint references public.fin_accounts(id),
  repeat text not null default 'none' check (repeat in ('none', 'weekly', 'monthly')),
  status text not null default 'planned' check (status in ('planned', 'paid', 'cancelled')),
  operation_id bigint references public.fin_operations(id) on delete set null,
  comment text,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now()
);
create index if not exists fin_planned_due_idx on public.fin_planned_payments (due_date);

-- ── План ОПИУ: месяц × статья × магазин (null = вся компания) ─────────────
create table if not exists public.fin_pnl_plan (
  id bigint generated by default as identity primary key,
  plan_month date not null, -- первое число месяца
  category_id bigint not null references public.fin_categories(id) on delete cascade,
  store text references public.stores(code),
  amount numeric not null default 0,
  created_at timestamptz not null default now()
);
create unique index if not exists fin_pnl_plan_unique
  on public.fin_pnl_plan (plan_month, category_id, coalesce(store, ''));

-- ── Настройки («Условия») ────────────────────────────────────────────────
