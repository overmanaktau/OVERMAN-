-- Журнал сгорания бонусов: каждую ночь бонусы, которым исполнилось 4 месяца с начисления, списываются в МойСклад (сам МойСклад их не сжигает).
-- Пишет только сервер (маршрут /api/kassa/expire-bonus), читать из браузера нельзя (RLS без политик).
create table if not exists public.kassa_bonus_expiry_log (
  id bigint generated by default as identity primary key,
  run_date date not null,
  client_ms_id text not null,
  client_name text not null default '',
  phone text not null default '',
  value numeric not null,
  tx_id text,
  created_at timestamptz not null default now()
);
create index if not exists kassa_bonus_expiry_log_date on public.kassa_bonus_expiry_log (run_date);
alter table public.kassa_bonus_expiry_log enable row level security;
