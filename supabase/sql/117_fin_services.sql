-- «Оплаты»: постоянные расходы на услуги и лицензии (вайфай, лицензия МойСклад и т. п.) со сроком, до которого оплачено, — чтобы заранее знать, что и куда платить.
create table if not exists public.fin_services (
  id bigint generated by default as identity primary key,
  name text not null,                       -- что оплачивать
  pay_to text,                              -- куда платить (кому, где, реквизиты)
  amount numeric,                           -- сумма платежа, ₸
  store text references public.stores(code), -- null — общий для всех магазинов
  paid_until date not null,                 -- срок: до какого числа оплачено
  comment text,
  created_at timestamptz not null default now()
);
create index if not exists fin_services_paid_until_idx on public.fin_services (paid_until);

alter table public.fin_services enable row level security;
drop policy if exists fin_services_select on public.fin_services;
create policy fin_services_select on public.fin_services
  for select using (
    public.has_access('finance.payments', 'view')
    and (store is null and public.has_all_stores_access() or store is not null and public.has_store_access(store))
  );
drop policy if exists fin_services_write on public.fin_services;
create policy fin_services_write on public.fin_services
  for all using (
    public.has_access('finance.payments', 'edit')
    and (store is null and public.has_all_stores_access() or store is not null and public.has_store_access(store))
  )
  with check (
    public.has_access('finance.payments', 'edit')
    and (store is null and public.has_all_stores_access() or store is not null and public.has_store_access(store))
  );

create or replace function public.has_finance_view()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.has_access('finance.overview', 'view')
      or public.has_access('finance.dds', 'view')
      or public.has_access('finance.opiu', 'view')
      or public.has_access('finance.debts', 'view')
      or public.has_access('finance.planned', 'view')
      or public.has_access('finance.payments', 'view')
      or public.has_access('finance.settings', 'view');
$$;
