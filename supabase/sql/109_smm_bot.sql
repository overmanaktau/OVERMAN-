-- Бот для СММ (токен TELEGRAM_SMM_BOT_TOKEN): роли СММ Актау / СММ Актобе / Маркетолог / Администратор, таргет, истории, аналитика постов,
-- продажи по категориям. Все таблицы читает и пишет только сервер (service role), из браузера они недоступны (RLS без политик).

create table if not exists public.smm_users (
  id bigint generated by default as identity primary key,
  telegram_user_id bigint not null unique,
  telegram_chat_id bigint not null,
  username text,
  name text not null default '',
  role text not null check (role in ('smm_aktau', 'smm_aktobe', 'marketer', 'admin')),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'disabled', 'left')),
  awaiting text,            -- ждём от человека ввод (например, свой период), null — ничего не ждём
  state jsonb,              -- временный выбор (категории для «Посмотреть товары» и т. п.)
  requested_at timestamptz not null default now(),
  decided_at timestamptz,
  decided_by text,
  created_at timestamptz not null default now()
);
alter table public.smm_users enable row level security;

-- Чтобы повторный запуск расписания не слал одно и то же дважды.
create table if not exists public.smm_messages_sent (
  user_id bigint not null references public.smm_users(id) on delete cascade,
  kind text not null,
  ref_date date not null,
  sent_at timestamptz not null default now(),
  primary key (user_id, kind, ref_date)
);
alter table public.smm_messages_sent enable row level security;

-- Публикации в таргете: что было включено в прошлую проверку (объявления одного поста объединены).
create table if not exists public.smm_target_posts (
  city text not null,
  post_key text not null,               -- id поста в Instagram (или ссылка)
  name text not null default '',
  permalink text,
  ad_ids jsonb not null default '[]',
  is_active boolean not null default true,
  miss int not null default 0,           -- сколько проверок подряд пост не был активен
  started_at timestamptz not null default now(),
  ended_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (city, post_key)
);
alter table public.smm_target_posts enable row level security;

-- Истории: каждый час забираем активные и их цифры, потому что через 24 часа Instagram их больше не отдаёт.
create table if not exists public.smm_story_log (
  story_id text primary key,
  city text not null,
  media_type text,
  permalink text,
  cover_path text,                       -- обложка, сохранённая в хранилище smm-stories
  posted_at timestamptz not null,
  views int not null default 0,
  reach int not null default 0,
  replies int not null default 0,
  navigation int not null default 0,
  shares int not null default 0,
  interactions int not null default 0,
  first_seen timestamptz not null default now(),
  last_seen timestamptz not null default now()
);
create index if not exists smm_story_log_city_posted on public.smm_story_log (city, posted_at);
alter table public.smm_story_log enable row level security;

insert into storage.buckets (id, name, public) values ('smm-stories', 'smm-stories', true) on conflict (id) do nothing;

-- Продажи по верхним категориям за период (штуки и сумма, с учётом возвратов — как в таблице продаж по товарам).
create or replace function public.smm_category_sales(p_store text, p_from date, p_to date)
returns table (category text, qty numeric, revenue numeric)
language sql
stable
as $$
  select coalesce(p.top_category, 'Без категории') as category, sum(s.quantity) as qty, sum(s.revenue) as revenue
  from public.moysklad_product_sales_daily s
  left join public.moysklad_products p on p.id = s.product_ms_id
  where s.store = p_store and s.sale_date between p_from and p_to
  group by coalesce(p.top_category, 'Без категории')
  having sum(s.quantity) <> 0
  order by sum(s.quantity) desc
$$;

-- Товары выбранных категорий за период.
create or replace function public.smm_category_products(p_store text, p_from date, p_to date, p_categories text[])
returns table (category text, product_name text, qty numeric, revenue numeric)
language sql
stable
as $$
  select coalesce(p.top_category, 'Без категории') as category, max(s.product_name) as product_name, sum(s.quantity) as qty, sum(s.revenue) as revenue
  from public.moysklad_product_sales_daily s
  left join public.moysklad_products p on p.id = s.product_ms_id
  where s.store = p_store and s.sale_date between p_from and p_to
    and coalesce(p.top_category, 'Без категории') = any(p_categories)
  group by coalesce(p.top_category, 'Без категории'), s.product_ms_id
  having sum(s.quantity) <> 0
  order by coalesce(p.top_category, 'Без категории'), sum(s.quantity) desc
$$;
